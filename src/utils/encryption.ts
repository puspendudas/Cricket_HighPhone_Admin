import CryptoJS from 'crypto-js';

const TRANSIT_KEY = (import.meta as any).env?.VITE_TRANSIT_ENCRYPTION_KEY || 'cricket-transit-secret-key-2026';

/**
 * Legacy Caesar cipher (ROT-10) fallback
 */
export const legacyCaesarShift = (text: string, shift: number = 10): string => {
  if (!text) return '';
  let result = '';
  for (let i = 0; i < text.length; i += 1) {
    const charCode = text.charCodeAt(i);
    if (charCode >= 32 && charCode <= 126) {
      result += String.fromCharCode(((charCode - 32 + shift) % 95) + 32);
    } else {
      result += text.charAt(i);
    }
  }
  return result;
};

/**
 * Decrypts a transit-encrypted password for UI display.
 * Supports:
 * 1. Option C Transit AES: OpenSSL Salted format ("U2FsdGVkX1...") generated by server CryptoJS.AES
 * 2. Legacy ROT-10 fallback if any unmigrated transit response is received
 */
export const decrypt = (text: string, shift: number = 10): string => {
  if (!text) return '';
  if (typeof text !== 'string') return String(text);

  // 1. Option C: Transit AES (starts with CryptoJS Base64 prefix "U2FsdGVkX1")
  if (text.startsWith('U2FsdGVkX1')) {
    try {
      const bytes = CryptoJS.AES.decrypt(text, TRANSIT_KEY);
      const decrypted = bytes.toString(CryptoJS.enc.Utf8);
      if (decrypted) return decrypted;
    } catch (err) {
      console.error('[decrypt] Transit AES decryption error:', err);
    }
  }

  // 2. Legacy ROT-10 fallback
  return legacyCaesarShift(text, (95 - shift) % 95);
};

export const encrypt = (text: string, _shift: number = 10): string => {
  if (!text) return '';
  return CryptoJS.AES.encrypt(text, TRANSIT_KEY).toString();
};
